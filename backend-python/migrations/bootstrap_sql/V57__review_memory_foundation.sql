CREATE TABLE IF NOT EXISTS review_memory_sources (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  project_id BIGINT NOT NULL,
  kind VARCHAR(32) NOT NULL,
  origin VARCHAR(16) NOT NULL,
  title VARCHAR(255) NOT NULL,
  description TEXT NULL,
  state VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
  version INT NOT NULL DEFAULT 1,
  original_filename VARCHAR(255) NULL,
  media_type VARCHAR(100) NULL,
  original_bytes MEDIUMBLOB NULL,
  original_sha256 CHAR(64) NULL,
  extracted_text MEDIUMTEXT NULL,
  parser_version VARCHAR(64) NULL,
  parse_warnings_json TEXT NULL,
  source_feedback_id BIGINT NULL,
  feedback_digest CHAR(64) NULL,
  replacement_of_id BIGINT NULL,
  confirmed_by VARCHAR(128) NULL,
  confirmed_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  deleted_at DATETIME(3) NULL,
  UNIQUE KEY uk_review_memory_sources_feedback (source_feedback_id),
  KEY idx_review_memory_sources_project_state_kind (project_id, state, kind, id),
  KEY idx_review_memory_sources_project_sha (project_id, original_sha256)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS review_memory_entries (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  source_id BIGINT NOT NULL,
  section_key VARCHAR(128) NOT NULL,
  heading VARCHAR(255) NOT NULL,
  ordinal INT NOT NULL,
  content MEDIUMTEXT NOT NULL,
  target_type VARCHAR(32) NULL,
  issue_type VARCHAR(64) NULL,
  path_globs_json TEXT NULL,
  keywords_json TEXT NULL,
  load_mode VARCHAR(16) NOT NULL DEFAULT 'ON_DEMAND',
  state VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
  version INT NOT NULL DEFAULT 1,
  content_sha256 CHAR(64) NOT NULL,
  validation_errors_json TEXT NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  UNIQUE KEY uk_review_memory_entries_section (source_id, section_key),
  KEY idx_review_memory_entries_source_state_scope (source_id, state, load_mode, target_type, issue_type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS review_memory_writebacks (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  feedback_id BIGINT NOT NULL,
  idempotency_key CHAR(64) NOT NULL,
  feedback_digest CHAR(64) NOT NULL,
  confirmation_json MEDIUMTEXT NOT NULL,
  expected_source_version INT NULL,
  state VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(3) NOT NULL,
  lease_owner VARCHAR(128) NULL,
  lease_until DATETIME(3) NULL,
  source_id BIGINT NULL,
  last_error_code VARCHAR(64) NULL,
  confirmed_by VARCHAR(128) NULL,
  created_at DATETIME(3) NOT NULL,
  updated_at DATETIME(3) NOT NULL,
  finished_at DATETIME(3) NULL,
  UNIQUE KEY uk_review_memory_writebacks_idempotency (idempotency_key),
  KEY idx_review_memory_writebacks_due (state, next_attempt_at, id),
  KEY idx_review_memory_writebacks_lease (lease_until, state),
  KEY idx_review_memory_writebacks_feedback (feedback_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
