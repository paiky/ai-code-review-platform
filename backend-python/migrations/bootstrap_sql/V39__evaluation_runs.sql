CREATE TABLE IF NOT EXISTS evaluation_runs (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(255) NOT NULL,
  run_type VARCHAR(32) NOT NULL DEFAULT 'EVALUATION',
  sample_set_name VARCHAR(255) NULL,
  sample_set_json JSON NULL,
  project_id BIGINT NULL,
  provider VARCHAR(64) NULL,
  profile VARCHAR(64) NULL,
  model VARCHAR(128) NULL,
  prompt_hash VARCHAR(128) NULL,
  context_pack_version VARCHAR(64) NULL,
  retriever_version VARCHAR(64) NULL,
  rule_gap_version VARCHAR(64) NULL,
  baseline_json JSON NULL,
  candidate_json JSON NULL,
  status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  total_count INT NOT NULL DEFAULT 0,
  completed_count INT NOT NULL DEFAULT 0,
  failed_count INT NOT NULL DEFAULT 0,
  result_summary_json JSON NULL,
  duration_ms BIGINT NULL,
  notes TEXT NULL,
  started_at DATETIME(3) NULL,
  finished_at DATETIME(3) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  KEY idx_evaluation_runs_project_created (project_id, created_at),
  KEY idx_evaluation_runs_filters (project_id, provider, profile, run_type, status),
  KEY idx_evaluation_runs_status_created (status, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS evaluation_run_items (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  run_id BIGINT NOT NULL,
  case_id BIGINT NOT NULL,
  item_index INT NOT NULL DEFAULT 0,
  task_id BIGINT NULL,
  review_key VARCHAR(64) NULL,
  fingerprint VARCHAR(128) NULL,
  project_id BIGINT NOT NULL,
  provider VARCHAR(64) NULL,
  profile VARCHAR(64) NULL,
  risk_type VARCHAR(64) NULL,
  severity VARCHAR(32) NULL,
  context_status VARCHAR(32) NULL,
  verdict VARCHAR(64) NOT NULL DEFAULT 'UNKNOWN',
  status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
  duration_ms BIGINT NULL,
  baseline_summary_json JSON NULL,
  candidate_summary_json JSON NULL,
  result_summary_json JSON NULL,
  error_message VARCHAR(1024) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uk_evaluation_run_items_run_case (run_id, case_id),
  KEY idx_evaluation_run_items_run_status (run_id, status),
  KEY idx_evaluation_run_items_case (case_id),
  KEY idx_evaluation_run_items_project (project_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
